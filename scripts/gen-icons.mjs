#!/usr/bin/env node
// Generates the Go and Rust icon tables from icons/default-icons.json.
// The JSON holds Astryx's default glyphs (packages/core/src/Icon/defaultIcons.tsx, MIT,
// Meta Platforms, Inc.): each entry is the inner markup of a 24x24 SVG.
// Usage: node scripts/gen-icons.mjs
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url).pathname;
const icons = JSON.parse(readFileSync(root + 'icons/default-icons.json', 'utf8'));
const names = Object.keys(icons).sort();
const header = 'Code generated by scripts/gen-icons.mjs from icons/default-icons.json. DO NOT EDIT.';

const go = [
	`// ${header}`,
	'',
	'package canon',
	'',
	'var defaultIcons = map[string]glyph{',
	...names.map((n) => {
		const g = icons[n];
		return `\t${JSON.stringify(n)}: {solid: ${g.style === 'solid'}, strokeWidth: ${JSON.stringify(String(g.strokeWidth ?? 1.5))}, body: ${JSON.stringify(g.body)}},`;
	}),
	'}',
	''
];
writeFileSync(root + 'go/canon/icons_gen.go', go.join('\n'));
execFileSync('gofmt', ['-w', root + 'go/canon/icons_gen.go']);

const rs = [
	`// ${header}`,
	'',
	'use crate::icon::Glyph;',
	'',
	'/// Built-in glyph names, sorted.',
	`pub(crate) static DEFAULT_ICONS: [(&str, Glyph); ${names.length}] = [`,
	...names.map((n) => {
		const g = icons[n];
		return `    (${JSON.stringify(n)}, Glyph { solid: ${g.style === 'solid'}, stroke_width: ${JSON.stringify(String(g.strokeWidth ?? 1.5))}, body: r#"${g.body}"# }),`;
	}),
	'];',
	''
];
writeFileSync(root + 'rust/src/icons_gen.rs', rs.join('\n'));
execFileSync('rustfmt', ['--edition', '2024', root + 'rust/src/icons_gen.rs']);
console.log(`Generated ${names.length} icons.`);
